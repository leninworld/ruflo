"""Owned hosted source/overlay/document inputs, not a source loader or fetcher."""
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def owned(path):
    path = Path(path)
    assert path.is_absolute() and str(path).startswith('/work/') and '..' not in path.parts
    assert not path.is_symlink()
    return path


def safe(root, relative):
    assert isinstance(relative, str) and relative and not relative.startswith('/')
    parts = Path(relative).parts
    assert '..' not in parts and '.' not in parts
    result = Path(root)
    for part in parts:
        result /= part
        assert not result.is_symlink(), 'SYMLINK_INPUT_PATH'
    return result


def git(source, *args):
    return subprocess.run(['git', '-c', 'safe.directory=' + str(source), '-c', 'core.hooksPath=/dev/null',
                           '-C', str(source), *args], capture_output=True, text=True, timeout=30, check=True).stdout.strip()


def prepare(source, original, packet, plan, variant, documents=None):
    source, original, packet = owned(source), Path(original), Path(packet)
    assert not source.exists(), 'NO_SOURCE_OVERWRITE'
    assert git(original, 'rev-parse', 'HEAD') == plan['source_pin'], 'WRONG_SOURCE_PIN'
    assert not git(original, 'status', '--porcelain', '--untracked-files=all'), 'DIRTY_ORIGINAL_INPUT'
    for name, expected in plan['locked_inputs'].items():
        assert sha(safe(original, name)) == expected, 'LOCKED_INPUT_CHANGED_' + name
    shutil.copytree(original, source, symlinks=True)
    for row in plan['candidate_files']:
        target = safe(source, row['path'])
        assert (not target.exists()) if row['new'] else sha(target) == row['before_sha256'], 'BASELINE_SOURCE_CHANGED'
        if variant == 'candidate':
            data = safe(packet / 'candidate-files', row['path'])
            assert sha(data) == row['sha256'], 'CANDIDATE_PAYLOAD_CHANGED'
            target.parent.mkdir(parents=True, exist_ok=True)
            if row['new']:
                with target.open('xb') as output:
                    output.write(data.read_bytes())
            else:
                target.write_bytes(data.read_bytes())
    if documents is not None:
        assert variant == 'candidate'
        apply_documents(source, documents, plan)
    verify(source, plan, variant, documents)


def verify(source, plan, variant, documents=None):
    assert git(source, 'rev-parse', 'HEAD') == plan['source_pin']
    for name, expected in plan['locked_inputs'].items():
        assert sha(safe(source, name)) == expected, 'LOCK_CHANGED_' + name
    for row in plan['candidate_files']:
        target = safe(source, row['path'])
        if variant == 'candidate':
            assert sha(target) == row['sha256'], 'TESTED_PATCH_CHANGED_' + row['path']
        elif row['new']:
            assert not target.exists(), 'BASELINE_HAS_CANDIDATE_FILE'
        else:
            assert sha(target) == row['before_sha256'], 'BASELINE_INPUT_CHANGED'

    expected_tracked={row['path'] for row in plan['candidate_files'] if not row['new']} if variant=='candidate' else set()
    assert set(git(source,'diff','HEAD','--name-only').splitlines())==expected_tracked, 'UNEXPECTED_TRACKED_SOURCE_MUTATION'

    if variant == 'candidate' and documents is not None:
        generated = json.loads((Path(documents)/'generated-manifest.json').read_text())
        assert generated['source_pin'] == plan['source_pin'] and generated['patch_sha256'] == plan['patch_sha256']
        names = set()
        for row in generated['files']:
            names.add(row['path'])
            assert sha(safe(source, row['path'])) == row['sha256'], 'TESTED_GENERATED_DOC_CHANGED'
        assert {str(f.relative_to(source)) for f in (Path(source)/'docs/cli-reference').glob('*')} | {'docs/CLI-REFERENCE.md','scripts/cli-reference-native-findings.json'} == names, 'TESTED_DOC_INVENTORY_CHANGED'


def apply_documents(source, documents, plan):
    directory = Path(documents)
    manifest = json.loads((directory / 'generated-manifest.json').read_text())
    assert manifest['source_pin'] == plan['source_pin'] and manifest['patch_sha256'] == plan['patch_sha256']
    names = set()
    for row in manifest['files']:
        name = row['path']
        assert name in ['docs/CLI-REFERENCE.md','scripts/cli-reference-native-findings.json'] or (name.startswith('docs/cli-reference/') and name.endswith('.md'))
        assert name not in names; names.add(name)
        value = safe(directory, name)
        assert value.is_file() and sha(value) == row['sha256'] and value.stat().st_size == row['bytes']
        if name.endswith('.md'): assert value.read_text().startswith('<!-- Generated by scripts/generate-cli-reference.mjs.')
        else:
            snapshot=json.loads(value.read_text());assert snapshot['schema']==1 and isinstance(snapshot['entries'],list) and snapshot['entries']
        target = safe(source, name)
        assert not target.exists(), 'DO_NOT_OVERWRITE_PREEXISTING_DOCS'
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(value, target)
    assert 'docs/CLI-REFERENCE.md' in names and len(names) > 1
    actual = {str(f.relative_to(directory)) for f in (directory / 'docs').rglob('*') if f.is_file()}
    if (directory/'scripts/cli-reference-native-findings.json').is_file():actual.add('scripts/cli-reference-native-findings.json')
    assert actual == names, 'UNSEALED_GENERATED_DOCUMENTS'
    return manifest


